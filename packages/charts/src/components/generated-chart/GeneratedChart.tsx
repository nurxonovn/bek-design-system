import { useId, type HTMLAttributes, type ReactNode } from 'react';
import { Button, cx, EmptyState, Skeleton, Spinner } from '@bek/react';
import { AiInsightLine } from './AiInsightLine.js';
import { BookmarkGlyph, CodeGlyph, SparklesGlyph, TableGlyph } from './glyphs.js';

export type GeneratedChartState = 'default' | 'generating' | 'error';

export interface GeneratedChartProps extends Omit<HTMLAttributes<HTMLElement>, 'title'> {
  /** Figma `Title`: "Revenue by month, 2026". */
  title: ReactNode;
  /** `default` — chart, insight va amallar; `generating` — skeleton + spinner + qadam; `error` — Chart/Card Error. */
  state?: GeneratedChartState;
  /** Ma'lumot manbasi va qatorlar soni — doim ko'rsating: "Source: payments.csv · 1 240 rows". */
  source?: ReactNode;
  /** AI xulosa qatori (Chart/AI insight · Inline): avval topilma, keyin sabab. */
  insight?: ReactNode;
  /** Sarlavha qatori: "Generated by BEK AI". */
  generatedBy?: ReactNode;
  /** Vaqt: "Just now". */
  timestamp?: ReactNode;
  /** Generating: "Generating chart…". */
  generatingLabel?: ReactNode;
  /** Generating: "Step 2 of 3". */
  step?: ReactNode;
  /** Generating: model nima qilayotgani — "Reading 1 240 rows from payments.csv…". */
  progressNote?: ReactNode;
  /** Amallar (Button Flat-secondary). Berilgan callback'lar uchun tugma chiqadi. */
  onShowTable?: () => void;
  onShowCode?: () => void;
  onSave?: () => void;
  /** Qo'shimcha amallar sloti (standart tugmalardan keyin). */
  actions?: ReactNode;
  /** Error holat matni va "Try again". */
  errorTitle?: ReactNode;
  errorDescription?: ReactNode;
  onRetry?: () => void;
  /** Sarlavha darajasi — sahifa tuzilmasiga mos (standart h3). */
  headingLevel?: 2 | 3 | 4 | 5 | 6;
  /** Chart sloti — istalgan `@bek/charts` chart (odatda `ChartContainer` ichida). */
  children?: ReactNode;
}

/**
 * Figma "4.18 Chart · Generated chart": AI yordamchi foydalanuvchi ma'lumotidan yasagan chart kartasi —
 * AI belgisi, sarlavha, manba, chart sloti, AI insight va amallar (Table · Code · Save).
 */
export function GeneratedChart({
  title,
  state = 'default',
  source,
  insight,
  generatedBy = 'Generated by BEK AI',
  timestamp,
  generatingLabel = 'Generating chart…',
  step,
  progressNote,
  onShowTable,
  onShowCode,
  onSave,
  actions,
  errorTitle = "Couldn't build the chart",
  errorDescription = 'Check the data source and try again.',
  onRetry,
  headingLevel = 3,
  children,
  className,
  ...rest
}: GeneratedChartProps) {
  const Heading = `h${headingLevel}` as const;
  const titleId = useId();
  const generating = state === 'generating';
  const hasActions = onShowTable || onShowCode || onSave || actions != null;

  return (
    <section
      {...rest}
      className={cx('bek-generated-chart', `bek-generated-chart--${state}`, className)}
      aria-labelledby={titleId}
      aria-busy={generating || undefined}
    >
      <header className="bek-generated-chart__header">
        <span className="bek-generated-chart__status">
          {generating ? (
            <Spinner size={16} label={null} className="bek-generated-chart__spinner" />
          ) : (
            <SparklesGlyph className="bek-generated-chart__mark" />
          )}
          {generating ? generatingLabel : generatedBy}
        </span>
        {(generating ? step : timestamp) != null && (
          <span className="bek-generated-chart__meta">{generating ? step : timestamp}</span>
        )}
      </header>

      {generating ? (
        <>
          <Heading id={titleId} className="bek-chart__sr">
            {title}
          </Heading>
          <div className="bek-generated-chart__skeleton" aria-hidden="true">
            <Skeleton shape="title" />
            <Skeleton shape="text" lines={3} />
            <Skeleton shape="rect" className="bek-generated-chart__plot-skeleton" />
          </div>
          {progressNote != null && (
            <p className="bek-generated-chart__note" role="status">
              {progressNote}
            </p>
          )}
        </>
      ) : (
        <>
          <div className="bek-generated-chart__heading">
            <Heading id={titleId} className="bek-generated-chart__title">
              {title}
            </Heading>
            {source != null && <p className="bek-generated-chart__source">{source}</p>}
          </div>
          <div className="bek-generated-chart__slot">
            {state === 'error' ? (
              <EmptyState
                size="s"
                role="alert"
                title={errorTitle}
                description={errorDescription}
                primaryAction={onRetry ? { label: 'Try again', onClick: onRetry } : undefined}
              />
            ) : (
              children
            )}
          </div>
          {state === 'default' && insight != null && <AiInsightLine>{insight}</AiInsightLine>}
          {state === 'default' && hasActions && (
            <div className="bek-generated-chart__actions">
              {onShowTable && (
                <Button
                  variant="flat-secondary"
                  startIcon={<TableGlyph className="bek-generated-chart__icon" />}
                  onClick={onShowTable}
                >
                  Table
                </Button>
              )}
              {onShowCode && (
                <Button
                  variant="flat-secondary"
                  startIcon={<CodeGlyph className="bek-generated-chart__icon" />}
                  onClick={onShowCode}
                >
                  Code
                </Button>
              )}
              {onSave && (
                <Button
                  variant="flat-secondary"
                  startIcon={<BookmarkGlyph className="bek-generated-chart__icon" />}
                  onClick={onSave}
                >
                  Save
                </Button>
              )}
              {actions}
            </div>
          )}
        </>
      )}
    </section>
  );
}
